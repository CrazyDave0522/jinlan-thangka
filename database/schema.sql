CREATE FUNCTION thangka.set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at = clock_timestamp();
    RETURN NEW;
END;
$$;
CREATE TRIGGER set_updated_at BEFORE UPDATE ON thangka.artists
    FOR EACH ROW EXECUTE FUNCTION thangka.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON thangka.artworks
    FOR EACH ROW EXECUTE FUNCTION thangka.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON thangka.images
    FOR EACH ROW EXECUTE FUNCTION thangka.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON thangka.sources
    FOR EACH ROW EXECUTE FUNCTION thangka.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON thangka.artwork_artists
    FOR EACH ROW EXECUTE FUNCTION thangka.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON thangka.artist_sources
    FOR EACH ROW EXECUTE FUNCTION thangka.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON thangka.artwork_sources
    FOR EACH ROW EXECUTE FUNCTION thangka.set_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON thangka.image_sources
    FOR EACH ROW EXECUTE FUNCTION thangka.set_updated_at();

