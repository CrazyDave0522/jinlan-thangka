-- ===== Excel import rules (implemented by future import tooling, not by this schema script) =====
-- 1. Preserve the original Excel for each batch. Preview and resolve ambiguities manually before transactional writes.
-- 2. Import order: sources, artists, artworks, artist relationships, images, source relationships.
-- 3. Normalize nullable blanks to NULL and blank arrays to {}; split aliases/styles/institutions on fullwidth semicolons (U+FF1B).
--    Preserve teachers_text as written, so splitting does not lose lineage relationships or temporal context.
-- 4. After the first import, persist a mapping from original records to internal UUIDs.
--    Without IDs, renamed records or changed paths cannot reliably be recognized; never upsert using row numbers or names alone.
--    Subsequent files without persistent mappings require candidate and add/update/conflict previews, then manual confirmation.
-- 5. Match identically named artists using region, institutions, and life dates; match identically titled artworks using artists, collections,
--    accession numbers, and primary image paths. Never silently associate records with multiple or zero matches.
-- 6. Do not create artist records for unknown artists. Use not_recorded for unspecified attribution;
--    use unknown only when the artist is explicitly unknown. These states are distinct.
-- 7. Create separate artwork_artists records for collaborators. Record disputed attribution and evidence per candidate;
--    artwork_sources.evidence_notes must identify the candidate supported by the source.
-- 8. The artwork template primary image path must match the image template primary flag; report conflicts rather than silently overwrite.
--    When changing the primary image, clear the old flag before setting the new one in the same transaction.
-- 9. Resolve source titles or URLs to sources.id before writing the three source relationship types; manually confirm identical titles with
--    unclear editions. Store citation pages and supported facts on relationships; preserve collection wording on the source record.
-- 10. Sources without URLs, such as interviews, are allowed; temporary signed URLs must not serve as stable image identifiers.
-- 11. Blank review status is NULL; pending review=pending, reviewed=verified, disputed=disputed.
--     Reviewed means the information was checked; it does not authenticate the artwork or confirm image permissions.
-- 12. Preserve period wording as text; numeric dimensions must be >0; do not invent exact years from circa 18th century.
-- 13. For workshop or school attribution without a named individual, retain the overall attribution without inventing an artist.
-- 14. This schema stores human-curated information only. AI inferences, image vectors, chats, and review history belong in separate future tables;
--     unreviewed model output must not automatically overwrite original knowledge fields.
-- 15. Configure application accounts and access policies separately at deployment; this script does not create a public browser API.

