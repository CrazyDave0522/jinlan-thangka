-- Thangka archive: initial PostgreSQL schema
-- Requires PostgreSQL 13+ and a UTF-8 database; initialization script for a new database.
-- Creates structure only; does not import Excel, modify templates, or include collected data.
-- Execute the entire script once. Existing objects cause an error and rollback to surface version differences.
-- Collectors do not supply internal IDs; omit id on INSERT to generate a UUID in the database.
-- Four core tables: artists / artworks / images / sources.
-- Four relationship tables: artwork_artists / artist_sources / artwork_sources / image_sources.
-- Names, artwork titles, and source titles are not unique; duplicates, editions, and attribution disputes are allowed.
-- Image rights belong to image records; an accessible URL does not grant display or vision-model processing rights.
-- Does not create public access permissions, login accounts, RLS policies, or AI runtime tables.

BEGIN;
CREATE SCHEMA thangka;

CREATE TABLE thangka.artists (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    display_name text NOT NULL CHECK (btrim(display_name) <> ''),
    name_bo text,
    name_en text,
    aliases text[] NOT NULL DEFAULT '{}',
    gender text CHECK (gender IN ('male', 'female', 'other', 'not_stated')),
    birth_period_text text,
    death_period_text text,
    region_text text,
    styles text[] NOT NULL DEFAULT '{}',
    institutions text[] NOT NULL DEFAULT '{}',
    teachers_text text,
    active_period_text text,
    biography text,
    official_url text,
    collected_by text,
    collected_on date,
    review_status text CHECK (review_status IN ('pending', 'verified', 'disputed')),
    notes text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE thangka.artworks (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    title text NOT NULL CHECK (btrim(title) <> ''),
    title_bo text,
    title_en text,
    alternative_titles text[] NOT NULL DEFAULT '{}',
    attribution_status text NOT NULL DEFAULT 'not_recorded'
        CHECK (attribution_status IN ('not_recorded', 'confirmed', 'attributed',
            'workshop', 'circle_or_school', 'unknown', 'disputed')),
    attribution_notes text,
    creation_period_text text,
    -- Optional normalized years for internal use; collectors need not provide them. Populate only with evidence.
    creation_year_start integer,
    creation_year_end integer,
    dating_notes text,
    styles text[] NOT NULL DEFAULT '{}',
    subject_primary text,
    subject_details text,
    iconography_notes text,
    materials_text text,
    technique_text text,
    height_cm numeric CHECK (height_cm > 0),
    width_cm numeric CHECK (width_cm > 0),
    dimensions_notes text,
    collection_name text,
    accession_number text,
    collection_location text,
    provenance_notes text,
    description text,
    collected_by text,
    collected_on date,
    review_status text CHECK (review_status IN ('pending', 'verified', 'disputed')),
    notes text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (creation_year_start IS NULL OR creation_year_end IS NULL
           OR creation_year_start <= creation_year_end)
);

CREATE TABLE thangka.sources (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    title text NOT NULL CHECK (btrim(title) <> ''),
    source_type text CHECK (source_type IN ('institution_archive', 'book', 'paper',
                                          'webpage', 'interview', 'other')),
    author_or_organization text,
    publication_year integer,
    publisher_or_journal text,
    edition_text text,
    url text,
    doi_or_isbn text,
    locator_notes text,
    accessed_on date,
    supports_notes text,
    reliability_notes text,
    rights_notes text,
    collected_by text,
    notes text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE thangka.images (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    artwork_id uuid NOT NULL REFERENCES thangka.artworks(id) ON DELETE RESTRICT,
    storage_locator text NOT NULL CHECK (btrim(storage_locator) <> ''),
    thumbnail_locator text,
    image_type text CHECK (image_type IN ('full', 'detail', 'inscription', 'back',
                                        'mounting', 'other')),
    is_primary boolean NOT NULL DEFAULT false,
    caption text,
    photographer_or_provider text,
    rights_status text NOT NULL DEFAULT 'pending'
        CHECK (rights_status IN ('pending', 'public_domain', 'authorized',
                                 'open_license', 'copyrighted')),
    license_or_permission_reference text,
    permission_notes text,
    quality_notes text,
    -- Generated by import or image-processing tools, not entered in collection templates.
    sha256 text CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    pixel_width integer CHECK (pixel_width > 0),
    pixel_height integer CHECK (pixel_height > 0),
    mime_type text,
    byte_size bigint CHECK (byte_size > 0),
    collected_by text,
    collected_on date,
    review_status text CHECK (review_status IN ('pending', 'verified', 'disputed')),
    notes text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (artwork_id, storage_locator)
);

-- At most one primary image per artwork; having none is allowed. Only images.is_primary records this state.
-- Do not duplicate the primary image path or ID in artworks, to avoid inconsistent records.
CREATE UNIQUE INDEX images_one_primary_per_artwork
    ON thangka.images (artwork_id) WHERE is_primary;

-- An artwork may have multiple artists, and an artist may have multiple artworks.
-- Do not create an "Unknown artist" placeholder or invent relationships when the artist is unknown.
-- Record overall artwork attribution separately from the relationship to each candidate artist.
CREATE TABLE thangka.artwork_artists (
    artwork_id uuid NOT NULL REFERENCES thangka.artworks(id) ON DELETE RESTRICT,
    artist_id uuid NOT NULL REFERENCES thangka.artists(id) ON DELETE RESTRICT,
    role text NOT NULL DEFAULT 'creator'
        CHECK (role IN ('creator', 'collaborator', 'workshop_of', 'circle_of', 'other')),
    attribution_status text NOT NULL DEFAULT 'not_recorded'
        CHECK (attribution_status IN ('not_recorded', 'confirmed', 'attributed', 'disputed')),
    attribution_notes text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (artwork_id, artist_id, role)
);

-- On source relationships, locator stores citation pages and supported_field identifies the supported field.
-- evidence_notes stores facts, attribution claims, or conflicts. Use empty strings for unspecified fields/pages.
-- A source may support multiple records; a field may have multiple conflicting sources.

CREATE TABLE thangka.artist_sources (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    artist_id uuid NOT NULL REFERENCES thangka.artists(id) ON DELETE RESTRICT,
    source_id uuid NOT NULL REFERENCES thangka.sources(id) ON DELETE RESTRICT,
    supported_field text NOT NULL DEFAULT '',
    locator text NOT NULL DEFAULT '',
    evidence_notes text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (artist_id, source_id, supported_field, locator)
);

CREATE TABLE thangka.artwork_sources (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    artwork_id uuid NOT NULL REFERENCES thangka.artworks(id) ON DELETE RESTRICT,
    source_id uuid NOT NULL REFERENCES thangka.sources(id) ON DELETE RESTRICT,
    supported_field text NOT NULL DEFAULT '',
    locator text NOT NULL DEFAULT '',
    evidence_notes text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (artwork_id, source_id, supported_field, locator)
);

CREATE TABLE thangka.image_sources (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    image_id uuid NOT NULL REFERENCES thangka.images(id) ON DELETE RESTRICT,
    source_id uuid NOT NULL REFERENCES thangka.sources(id) ON DELETE RESTRICT,
    supported_field text NOT NULL DEFAULT '',
    locator text NOT NULL DEFAULT '',
    evidence_notes text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (image_id, source_id, supported_field, locator)
);

-- Name indexes are not unique; multiple search matches require manual confirmation.
CREATE INDEX artists_display_name_idx ON thangka.artists(display_name);
CREATE INDEX artists_aliases_idx ON thangka.artists USING gin(aliases);
CREATE INDEX artworks_title_idx ON thangka.artworks(title);
CREATE INDEX artworks_subject_idx ON thangka.artworks(subject_primary);
CREATE INDEX artworks_collection_idx ON thangka.artworks(collection_name, accession_number);
CREATE INDEX sources_title_idx ON thangka.sources(title);
CREATE INDEX sources_url_idx ON thangka.sources(url);
CREATE INDEX images_storage_locator_idx ON thangka.images(storage_locator);
CREATE INDEX images_sha256_idx ON thangka.images(sha256) WHERE sha256 IS NOT NULL;
CREATE INDEX artwork_artists_artist_idx ON thangka.artwork_artists(artist_id);
CREATE INDEX artist_sources_source_idx ON thangka.artist_sources(source_id);
CREATE INDEX artwork_sources_source_idx ON thangka.artwork_sources(source_id);
